type ElementFor<S extends string> = S extends keyof HTMLElementTagNameMap ? HTMLElementTagNameMap[S]
 : S extends `meta${string}` ? HTMLMetaElement : S extends `details${string}` ? HTMLDetailsElement : S extends `#${infer Id}` ? Id extends keyof ElementIds ? ElementIds[Id] : HTMLElement
 : S extends `button${string}` ? HTMLButtonElement
 : S extends `input${string}` ? HTMLInputElement
 : S extends `a[${string}` ? HTMLAnchorElement : HTMLElement;
export function query<S extends string>(selector:S,root:ParentNode=document):ElementFor<S> {
 const element=root.querySelector(selector);
 if(!element)throw new Error("Missing lecture control: "+selector);
 return element as ElementFor<S>;
}
export function byId<S extends string>(id:S):ElementFor<`#${S}`> { return query(`#${id}`); }
export function all<S extends string>(selector:S,root:ParentNode=document):NodeListOf<ElementFor<S>> {
 return root.querySelectorAll(selector) as NodeListOf<ElementFor<S>>;
}
